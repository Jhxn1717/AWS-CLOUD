const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');const os=require('node:os');const path=require('node:path');
const {ProcessManager}=require('../dist/services/ProcessManager');
const {ProcessModel}=require('../dist/models/ProcessModel');
const {ProjectModel}=require('../dist/models/ProjectModel');
test('stop waits until the real child exits and releases its working directory',async t=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'mycloud-stop-test-'));
 const id='stop-test-'+path.basename(root);
 t.after(async()=>{await ProcessManager.stop(id,true);assert.equal(path.dirname(root),os.tmpdir());assert.ok(path.basename(root).startsWith('mycloud-stop-test-'));fs.rmSync(root,{recursive:true,force:true});});
 t.mock.method(ProcessModel,'create',async()=>({id:'isolated-test'}));
 for(const method of ['updatePid','updateStatus'])t.mock.method(ProcessModel,method,async()=>{});
 for(const method of ['update','updateStatus'])t.mock.method(ProjectModel,method,async()=>{});
 const pid=await ProcessManager.start({projectId:id,command:process.execPath,args:['-e','setInterval(()=>{},1000)'],workingDir:root,port:4006,envVars:{}});
 await ProcessManager.stop(id);
 assert.equal(ProcessManager.isRunning(id),false);
 assert.throws(()=>process.kill(pid,0));
 fs.rmdirSync(root);
});
